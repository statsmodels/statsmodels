## Reference values for statsmodels.tsa.vector_ar.vecm.VECM
##
## urca::ca.jo with spec = "transitory" (the VECM form of statsmodels,
## Delta y_t = Pi y_{t-1} + Gamma_1 Delta y_{t-1} + ...), urca::cajorls and
## vars::vec2var on the Danish data that ships with statsmodels as
## statsmodels/datasets/danish_data/data.csv (identical to urca::denmark).
## K of ca.jo is k_ar_diff + 1. The cases map to VECM as
##
##   ecdet = "none"  -> deterministic = "co"   (unrestricted constant)
##   ecdet = "const" -> deterministic = "ci"   (constant in the relation)
##   ecdet = "trend" -> deterministic = "coli" (unrestricted constant and
##                                              trend in the relation)
##   season = 4      -> seasons = 4, first_season = 0 (centered dummies)
##
## The trend of ca.jo is 1, 2, ..., N at y_{t-1}, which is the trend of
## VECM, so the constant of "coli" is comparable as well. cajorls normalizes
## beta so that its first r rows are the identity, as VECM does. vec2var
## gives the VAR representation, its residuals (sigma_u = crossprod / T, the
## ML estimate of VECM), the log-likelihood, the MA matrices Phi, the
## orthogonalized MA matrices Psi (Cholesky factor of sigma_u) and the
## forecasts with 95% intervals.
##
## Python test is: statsmodels/tsa/vector_ar/tests/test_vecm.py
## ::test_vecm_urca_vars
##
## Run with R 4.6.2, urca 1.3.4 and vars 1.6.1 (on Windows):
##   Rscript results_vecm_urca.R > results_vecm_urca.py
## install.packages(c("urca", "vars"))
suppressMessages({
  library(urca)
  library(vars)
})

danish <- read.csv("../../../../datasets/danish_data/data.csv")
y <- as.matrix(danish[, c("lrm", "lry", "ibo", "ide")])
data(denmark)
stopifnot(isTRUE(all.equal(unname(y), unname(as.matrix(denmark[, c("LRM", "LRY", "IBO", "IDE")])),
                           tolerance = 1e-12)))

num <- function(x) sprintf("%.16e", x)
vec <- function(x) paste0("[", paste(num(x), collapse = ", "), "]")
mat <- function(m) {
  m <- as.matrix(m)
  rows <- apply(m, 1, vec)
  paste0("np.array(\n        [\n", paste0("            ", rows, ",", collapse = "\n"),
         "\n        ]\n    )")
}
arr3 <- function(a) {
  ## (K, K, h) array of vars as a (h, K, K) array
  mats <- sapply(seq_len(dim(a)[3]), function(i) {
    rows <- apply(a[, , i], 1, vec)
    paste0("            [\n", paste0("                ", rows, ",", collapse = "\n"),
           "\n            ],")
  })
  paste0("np.array(\n        [\n", paste(mats, collapse = "\n"), "\n        ]\n    )")
}

cases <- list(
  co = list(ecdet = "none", season = NULL, K = 2, r = 1),
  ci = list(ecdet = "const", season = NULL, K = 2, r = 1),
  coli = list(ecdet = "trend", season = NULL, K = 3, r = 2),
  co_seasons = list(ecdet = "none", season = 4, K = 2, r = 1)
)

cat('"""\n')
cat("Reference values for VECM from urca::ca.jo, urca::cajorls and vars::vec2var\n\n")
cat("Generated by results_vecm_urca.R (R ", paste(R.version$major, R.version$minor, sep = "."),
    ", urca ", as.character(packageVersion("urca")), ", vars ",
    as.character(packageVersion("vars")), "). Do not edit.\n", sep = "")
cat('"""\n\n')
cat("import numpy as np\n\n")
cat("results = {}\n")

n_ahead <- 5
for (name in names(cases)) {
  case <- cases[[name]]
  cajo <- ca.jo(y, type = "trace", ecdet = case$ecdet, K = case$K,
                spec = "transitory", season = case$season)
  r <- case$r
  ls <- cajorls(cajo, r = r)
  coefs <- coef(ls$rlm)
  rn <- rownames(coefs)
  alpha <- t(coefs[grepl("^ect", rn), , drop = FALSE])
  gamma <- t(coefs[grepl("\\.dl[0-9]+$", rn), , drop = FALSE])
  v2v <- vec2var(cajo, r = r)
  sigma_u <- crossprod(resid(v2v)) / v2v$obs
  pred <- predict(v2v, n.ahead = n_ahead, ci = 0.95)
  fcst <- sapply(pred$fcst, function(f) f[, "fcst"])
  lower <- sapply(pred$fcst, function(f) f[, "lower"])
  upper <- sapply(pred$fcst, function(f) f[, "upper"])

  cat("\nresults[\"", name, "\"] = {\n", sep = "")
  cat("    \"k_ar_diff\": ", case$K - 1, ",\n", sep = "")
  cat("    \"coint_rank\": ", r, ",\n", sep = "")
  cat("    \"beta\": ", mat(ls$beta), ",\n", sep = "")
  cat("    \"alpha\": ", mat(alpha), ",\n", sep = "")
  cat("    \"gamma\": ", mat(gamma), ",\n", sep = "")
  if ("constant" %in% rn) {
    cat("    \"const\": ", vec(coefs["constant", ]), ",\n", sep = "")
  }
  if (!is.null(case$season)) {
    cat("    \"seasonal\": ", mat(t(coefs[grepl("^sd", rn), , drop = FALSE])), ",\n", sep = "")
  }
  cat("    \"var_rep\": ", arr3(simplify2array(v2v$A)), ",\n", sep = "")
  cat("    \"sigma_u\": ", mat(sigma_u), ",\n", sep = "")
  cat("    \"llf\": ", num(as.numeric(logLik(v2v))), ",\n", sep = "")
  cat("    \"ma_rep\": ", arr3(Phi(v2v, nstep = n_ahead)), ",\n", sep = "")
  cat("    \"orth_ma_rep\": ", arr3(Psi(v2v, nstep = n_ahead)), ",\n", sep = "")
  cat("    \"fcst\": ", mat(fcst), ",\n", sep = "")
  cat("    \"lower\": ", mat(lower), ",\n", sep = "")
  cat("    \"upper\": ", mat(upper), ",\n", sep = "")
  cat("}\n")
}
